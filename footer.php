<script>
document.addEventListener('DOMContentLoaded', function() {
    const chatbotToggleBtn = document.getElementById('chatbotToggleBtn');
    const chatbotCloseBtn = document.getElementById('chatbotCloseBtn');
    const chatbotWindow = document.getElementById('chatbotWindow');
    const chatbotForm = document.getElementById('chatbotForm');
    const chatbotInput = document.getElementById('chatbotInput');
    const chatbotMessages = document.getElementById('chatbotMessages');
    const micBtn = document.getElementById('micBtn');
    
    // Chat memory array
    let chatHistory = [];

    function toggleChatbot() {
        if (chatbotWindow.classList.contains('opacity-0')) {
            chatbotWindow.classList.remove('opacity-0', 'translate-y-10', 'pointer-events-none');
            chatbotInput.focus();
        } else {
            chatbotWindow.classList.add('opacity-0', 'translate-y-10', 'pointer-events-none');
        }
    }

    if(chatbotToggleBtn) chatbotToggleBtn.addEventListener('click', toggleChatbot);
    if(chatbotCloseBtn) chatbotCloseBtn.addEventListener('click', toggleChatbot);

    function addMessage(text, isUser = false) {
        const msgDiv = document.createElement('div');
        msgDiv.className = `flex gap-2 ${isUser ? 'justify-end' : ''}`;
        
        let content = '';
        if (isUser) {
            content = `
                <div class="bg-indigo-600 p-3.5 rounded-2xl rounded-tr-none shadow-sm text-sm text-white max-w-[85%] leading-relaxed">
                    ${text}
                </div>
            `;
        } else {
            content = `
                <div class="w-8 h-8 rounded-full bg-indigo-100 flex items-center justify-center shrink-0 mt-1">
                    <i class="fas fa-user-md text-indigo-600 text-xs"></i>
                </div>
                <div class="bg-white p-3.5 rounded-2xl rounded-tl-none shadow-sm text-sm text-gray-700 max-w-[85%] border border-gray-100 leading-relaxed richtext-content">
                    ${text}
                </div>
            `;
        }
        
        msgDiv.innerHTML = content;
        chatbotMessages.appendChild(msgDiv);
        chatbotMessages.scrollTo({ top: chatbotMessages.scrollHeight, behavior: 'smooth' });
    }

    function addTypingIndicator() {
        const msgDiv = document.createElement('div');
        msgDiv.className = 'flex gap-2 typing-indicator';
        msgDiv.innerHTML = `
            <div class="w-8 h-8 rounded-full bg-indigo-100 flex items-center justify-center shrink-0 mt-1">
                <i class="fas fa-user-md text-indigo-600 text-xs"></i>
            </div>
            <div class="bg-white p-4 rounded-2xl rounded-tl-none shadow-sm border border-gray-100 flex items-center gap-1.5 h-[46px]">
                <div class="w-1.5 h-1.5 bg-indigo-400 rounded-full animate-bounce" style="animation-delay: -0.3s"></div>
                <div class="w-1.5 h-1.5 bg-indigo-400 rounded-full animate-bounce" style="animation-delay: -0.15s"></div>
                <div class="w-1.5 h-1.5 bg-indigo-400 rounded-full animate-bounce"></div>
            </div>
        `;
        chatbotMessages.appendChild(msgDiv);
        chatbotMessages.scrollTo({ top: chatbotMessages.scrollHeight, behavior: 'smooth' });
        return msgDiv;
    }

    if(chatbotForm) {
        chatbotForm.addEventListener('submit', async function(e) {
            e.preventDefault();
            const msg = chatbotInput.value.trim();
            if(!msg) return;

            addMessage(msg, true);
            chatbotInput.value = '';
            
            const loader = addTypingIndicator();

            try {
                // Better path resolution for the API
                const inSubfolder = window.location.pathname.includes('/pages/') || window.location.pathname.includes('/admin/');
                const apiPath = (typeof window.appBasePath !== 'undefined') ? 
                                window.appBasePath + 'api/chatbot.php' : 
                                (inSubfolder ? '../api/chatbot.php' : 'api/chatbot.php');
                
                const response = await fetch(apiPath, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ message: msg, history: chatHistory })
                });
                
                const data = await response.json();
                loader.remove();
                
                if(data.success) {
                    let formattedMsg = data.reply.replace(/\*\*(.*?)\*\*/g, '<strong class="text-indigo-900">$1</strong>');
                    formattedMsg = formattedMsg.replace(/\*(.*?)\*/g, '<em>$1</em>');
                    formattedMsg = formattedMsg.replace(/\n/g, '<br>');
                    addMessage(formattedMsg, false);
                    
                    // Add to memory
                    chatHistory.push({ role: "user", parts: [{ text: msg }] });
                    chatHistory.push({ role: "model", parts: [{ text: data.reply }] });
                    
                    // Keep history short to avoid payload bloat
                    if (chatHistory.length > 10) chatHistory = chatHistory.slice(-10);
                } else {
                    addMessage("Oops! My AI circuits are currently busy. Try again soon.", false);
                }
            } catch(err) {
                console.error(err);
                loader.remove();
                addMessage("Connection error. Please check your internet and try again.", false);
            }
        });
    }

    // Voice Typing feature
    if('webkitSpeechRecognition' in window || 'SpeechRecognition' in window) {
        const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
        const recognition = new SpeechRecognition();
        recognition.continuous = false;
        recognition.interimResults = false;
        // recognition.lang = 'en-US'; // Leave blank to auto-detect language

        recognition.onstart = function() {
            micBtn.classList.add('text-red-500', 'animate-pulse');
            chatbotInput.placeholder = 'Listening...';
        };

        recognition.onresult = function(event) {
            const transcript = event.results[0][0].transcript;
            chatbotInput.value = transcript;
        };

        recognition.onerror = function(event) {
            console.error('Speech recognition error', event.error);
        };

        recognition.onend = function() {
            micBtn.classList.remove('text-red-500', 'animate-pulse');
            chatbotInput.placeholder = 'I have a fever and weakness...';
            if(chatbotInput.value.trim() !== '') {
                chatbotForm.dispatchEvent(new Event('submit', { cancelable: true }));
            }
        };

        if(micBtn) {
            micBtn.addEventListener('click', function() {
                try {
                    recognition.start();
                } catch(e) {}
            });
        }
    } else {
        if(micBtn) micBtn.style.display = 'none'; // Hide mic if not supported
    }
});
</script>

